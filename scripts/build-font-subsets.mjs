import { createHash } from "node:crypto";
import {
  mkdir,
  readFile,
  readdir,
  rename,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import subsetFont from "subset-font";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceFontPath = join(root, "app/fonts/Huiwen-Mincho.ttf");
const generatedDir = join(root, "app/fonts/generated");
const criticalFontPath = join(generatedDir, "Huiwen-Mincho-critical.woff2");
const supplementFontPath = join(generatedDir, "Huiwen-Mincho-supplement.woff2");
const stylesheetPath = join(root, "app/fonts/huiwen-supplement.css");
const manifestPath = join(generatedDir, "manifest.json");

const printableAscii = Array.from({ length: 95 }, (_, index) =>
  String.fromCharCode(0x20 + index),
).join("");

const collectFiles = async (directory, test) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectFiles(path, test)));
    else if (test(path)) files.push(path);
  }
  return files.sort();
};

const uniqueCharacters = (text) =>
  [...new Set([...text])]
    .sort((left, right) => left.codePointAt(0) - right.codePointAt(0))
    .join("");

const unicodeRange = (text) => {
  const points = [...text].map((character) => character.codePointAt(0));
  const ranges = [];
  let start = points[0];
  let end = points[0];

  for (const point of points.slice(1)) {
    if (point === end + 1) {
      end = point;
      continue;
    }
    ranges.push([start, end]);
    start = point;
    end = point;
  }
  ranges.push([start, end]);

  return ranges
    .map(([first, last]) => {
      const from = first.toString(16).toUpperCase();
      const to = last.toString(16).toUpperCase();
      return first === last ? `U+${from}` : `U+${from}-${to}`;
    })
    .join(", ");
};

const atomicWrite = async (path, contents) => {
  const temporaryPath = `${path}.tmp`;
  await writeFile(temporaryPath, contents);
  await rename(temporaryPath, path);
};

const appFiles = await collectFiles(
  join(root, "app"),
  (path) => path.endsWith(".ts") || path.endsWith(".tsx"),
);
const storyFiles = await collectFiles(join(root, "content/stories"), (path) =>
  path.endsWith(".json"),
);
const sourceFont = await readFile(sourceFontPath);
const appSources = await Promise.all(appFiles.map((path) => readFile(path, "utf8")));
const storySources = await Promise.all(
  storyFiles.map((path) => readFile(path, "utf8")),
);
const stories = storySources.map((source) => JSON.parse(source));

// The critical face covers every headline plus fixed UI copy. It is the only
// custom face worth preloading: the masthead and story grids render correctly
// while the rest of an article remains free to use the instant system fallback.
const criticalCharacters = uniqueCharacters(
  [printableAscii, ...appSources, ...stories.map((story) => story.title)].join(""),
);
const allCharacters = uniqueCharacters(
  [criticalCharacters, ...storySources].join(""),
);
const criticalSet = new Set(criticalCharacters);
const supplementCharacters = uniqueCharacters(
  [...allCharacters].filter((character) => !criticalSet.has(character)).join(""),
);

const sourceHash = createHash("sha256")
  .update("huiwen-subsets-v1\0")
  .update(sourceFont)
  .update(criticalCharacters)
  .update(supplementCharacters)
  .digest("hex");

let currentManifest;
try {
  currentManifest = JSON.parse(await readFile(manifestPath, "utf8"));
  await Promise.all([stat(criticalFontPath), stat(supplementFontPath), stat(stylesheetPath)]);
} catch {
  currentManifest = null;
}

if (currentManifest?.sourceHash === sourceHash) {
  console.log("Huiwen Mincho subsets are up to date.");
  process.exit(0);
}

await mkdir(generatedDir, { recursive: true });

const [criticalFont, supplementFont] = await Promise.all([
  subsetFont(sourceFont, criticalCharacters, { targetFormat: "woff2" }),
  subsetFont(sourceFont, supplementCharacters, { targetFormat: "woff2" }),
]);

const stylesheet = `/* Generated by scripts/build-font-subsets.mjs. Do not edit. */
@font-face {
  font-family: "Huiwen Mincho Supplement";
  src: url("./generated/Huiwen-Mincho-supplement.woff2") format("woff2");
  font-style: normal;
  font-weight: 400;
  font-display: optional;
  unicode-range: ${unicodeRange(supplementCharacters)};
}
`;

await Promise.all([
  atomicWrite(criticalFontPath, criticalFont),
  atomicWrite(supplementFontPath, supplementFont),
  atomicWrite(stylesheetPath, stylesheet),
  atomicWrite(
    manifestPath,
    `${JSON.stringify(
      {
        sourceHash,
        sourceFont: relative(root, sourceFontPath),
        criticalCharacters: [...criticalCharacters].length,
        supplementCharacters: [...supplementCharacters].length,
        criticalBytes: criticalFont.length,
        supplementBytes: supplementFont.length,
      },
      null,
      2,
    )}\n`,
  ),
]);

console.log(
  `Built Huiwen Mincho subsets: ${(criticalFont.length / 1024).toFixed(0)} KiB critical + ${(supplementFont.length / 1024).toFixed(0)} KiB optional.`,
);
